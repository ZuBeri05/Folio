"""Convert Folio's HarmonyOS I18n.ets tables into a C header for the Switch port."""
import re
import sys

SRC = r"C:\Users\ZuBeri\Desktop\Folio\app\entry\src\main\ets\services\I18n.ets"
OUT = sys.argv[1]

text = open(SRC, encoding="utf-8").read()

LANGS = ["zh", "en", "ja", "ko", "fr", "es"]


def table(lang):
    m = re.search(
        r"private static readonly " + lang + r": Map<string, string> = I18n\.make\(\[(.*?)\]\);",
        text, re.S)
    body = m.group(1)
    items = re.findall(r'"((?:[^"\\]|\\.)*)"', body)
    pairs = list(zip(items[0::2], items[1::2]))
    return pairs


def cstr(s):
    out = []
    for ch in s:
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        else:
            out.append(ch)
    return '"' + "".join(out) + '"'


tables = {lang: table(lang) for lang in LANGS}

# Use the Chinese table's ordering as canonical; keep any extra keys from others.
keys = [k for k, _ in tables["zh"]]
for lang in LANGS:
    for k, _ in tables[lang]:
        if k not in keys:
            keys.append(k)

lines = []
lines.append("// Generated by tools/gen_i18n.py from the HarmonyOS original I18n.ets.")
lines.append("#pragma once")
lines.append("")
for lang in LANGS:
    d = dict(tables[lang])
    lines.append("static const char* const k_%s[][2] = {" % lang)
    for k in keys:
        v = d.get(k, "")
        lines.append("    {%s, %s}," % (cstr(k), cstr(v)))
    lines.append("};")
    lines.append("")

open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
print("keys:", len(keys), "->", OUT)
