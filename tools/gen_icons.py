"""Flatten the ArkUI SVG icons into C++ polyline geometry with baked colors.

Icons stay vector (polyline) rather than bitmap so they render crisply at any
size, and each shape keeps its own stroke/fill color from the original SVG.
"""
import os
import re
import sys

SRC = r"C:\Users\ZuBeri\Desktop\Folio\app\entry\src\main\resources\base\media"
OUT = sys.argv[1]


def tokenize(d):
    return re.findall(r"[MmLlHhVvCcSsQqTtAaZz]|-?\d*\.?\d+(?:[eE][-+]?\d+)?", d)


def parse_path(d, steps=20):
    toks = tokenize(d)
    i = 0
    x = y = 0.0
    sx = sy = 0.0
    subpaths = []
    cur = []
    cmd = None
    prev_ctrl = None

    def num():
        nonlocal i
        v = float(toks[i])
        i += 1
        return v

    def bez(p0, p1, p2, p3):
        out = []
        for k in range(1, steps + 1):
            t = k / steps
            u = 1 - t
            out.append((
                u*u*u*p0[0] + 3*u*u*t*p1[0] + 3*u*t*t*p2[0] + t*t*t*p3[0],
                u*u*u*p0[1] + 3*u*u*t*p1[1] + 3*u*t*t*p2[1] + t*t*t*p3[1]))
        return out

    while i < len(toks):
        t = toks[i]
        if re.match(r"[A-Za-z]", t):
            cmd = t
            i += 1
            if cmd in "Zz":
                if cur:
                    subpaths.append(cur)
                    cur = []
                x, y = sx, sy
                prev_ctrl = None
                continue
        rel = cmd.islower()
        c = cmd.upper()
        if c == "M":
            nx, ny = num(), num()
            if rel:
                nx, ny = x + nx, y + ny
            if cur:
                subpaths.append(cur)
            cur = [(nx, ny)]
            x, y = nx, ny
            sx, sy = nx, ny
            cmd = "l" if rel else "L"
            prev_ctrl = None
        elif c == "L":
            nx, ny = num(), num()
            if rel:
                nx, ny = x + nx, y + ny
            cur.append((nx, ny))
            x, y = nx, ny
            prev_ctrl = None
        elif c == "H":
            nx = num()
            if rel:
                nx = x + nx
            cur.append((nx, y))
            x = nx
        elif c == "V":
            ny = num()
            if rel:
                ny = y + ny
            cur.append((x, ny))
            y = ny
        elif c == "C":
            p1 = (num(), num()); p2 = (num(), num()); p3 = (num(), num())
            if rel:
                p1 = (x+p1[0], y+p1[1]); p2 = (x+p2[0], y+p2[1]); p3 = (x+p3[0], y+p3[1])
            cur.extend(bez((x, y), p1, p2, p3))
            prev_ctrl = p2
            x, y = p3
        elif c == "S":
            p2 = (num(), num()); p3 = (num(), num())
            if rel:
                p2 = (x+p2[0], y+p2[1]); p3 = (x+p3[0], y+p3[1])
            p1 = (2*x-prev_ctrl[0], 2*y-prev_ctrl[1]) if prev_ctrl else (x, y)
            cur.extend(bez((x, y), p1, p2, p3))
            prev_ctrl = p2
            x, y = p3
        else:
            i += 1
    if cur:
        subpaths.append(cur)
    return subpaths


def parse_svg(path):
    text = open(path, encoding="utf-8").read()
    vb = re.search(r'viewBox="([^"]+)"', text)
    vx, vy, vw, vh = [float(v) for v in vb.group(1).replace(",", " ").split()]
    shapes = []
    for m in re.finditer(r"<path\b([^>]*)/?>", text):
        attrs = m.group(1)
        dd = re.search(r'd="([^"]+)"', attrs)
        if not dd:
            continue
        stroke = re.search(r'stroke="([^"]+)"', attrs)
        fill = re.search(r'fill="([^"]+)"', attrs)
        sw = re.search(r'stroke-width="([\d.]+)"', attrs)
        subs = parse_path(dd.group(1))
        if stroke:
            shapes.append({"mode": "stroke", "color": stroke.group(1),
                           "width": float(sw.group(1)) if sw else 4.0, "subs": subs})
        if fill and fill.group(1) != "none":
            shapes.append({"mode": "fill", "color": fill.group(1), "width": 0.0, "subs": subs})
    return vw, vh, shapes


def hexInt(css):
    h = css.strip().lstrip("#")
    if len(h) == 3:
        h = "".join(ch * 2 for ch in h)
    return int(h, 16)


ICONS = [
    ("BananaOn", "ic_banana_on.svg"),
    ("BananaOff", "ic_banana_off.svg"),
    ("LemonOn", "ic_lemon_on.svg"),
    ("LemonOff", "ic_lemon_off.svg"),
    ("CarrotOn", "ic_carrot_on.svg"),
    ("CarrotOff", "ic_carrot_off.svg"),
    ("WatermelonOn", "ic_watermelon_on.svg"),
    ("WatermelonOff", "ic_watermelon_off.svg"),
    ("Tomato", "tomato.svg"),
]

lines = [
    "// Generated by tools/gen_icons.py from the HarmonyOS/ArkUI SVG assets.",
    "// Points are in the original 0..48 viewBox; the renderer scales them.",
    "#pragma once",
    "",
    "#include <cstdint>",
    "",
    "namespace folio {",
    "",
    "struct PolyPoint { float x; float y; unsigned char move; };",
    "",
    "/** One stroke or fill group inside an icon. */",
    "struct IconShape {",
    "    const PolyPoint* points;",
    "    int count;",
    "    float strokeWidth;  // 0 = filled polygon",
    "    uint32_t color;     // 0xRRGGBB",
    "};",
    "",
    "struct IconDef {",
    "    const IconShape* shapes;",
    "    int shapeCount;",
    "    float viewSize;",
    "};",
    "",
]

entries = []
for name, svg in ICONS:
    vw, vh, shapes = parse_svg(os.path.join(SRC, svg))
    shape_refs = []
    for si, sh in enumerate(shapes):
        pts = []
        for sub in sh["subs"]:
            pts.append((sub[0][0], sub[0][1], 1))
            for (px, py) in sub[1:]:
                pts.append((px, py, 0))
        arr = "k_%s_%d" % (name, si)
        body = ",".join("{%.3ff,%.3ff,%d}" % p for p in pts)
        lines.append("static const PolyPoint %s[] = {%s};" % (arr, body))
        shape_refs.append((arr, len(pts), sh["width"], hexInt(sh["color"])))
    lines.append("static const IconShape k_%s_shapes[] = {" % name)
    for (arr, cnt, sw, col) in shape_refs:
        lines.append("    {%s, %d, %.1ff, 0x%06X}," % (arr, cnt, sw, col))
    lines.append("};")
    lines.append("")
    entries.append((name, len(shape_refs), vw))

lines.append("const IconDef kIcons[] = {")
for name, cnt, vw in entries:
    lines.append("    {k_%s_shapes, %d, %.1ff}," % (name, cnt, vw))
lines.append("};")
lines.append("")
lines.append("enum IconIndex {")
for i, (name, _, _) in enumerate(entries):
    lines.append("    kIcon%s = %d," % (name, i))
lines.append("};")
lines.append("")
lines.append("}  // namespace folio")
lines.append("")

open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("wrote", OUT, "shapes:", sum(e[1] for e in entries))